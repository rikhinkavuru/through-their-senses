"""Write validation/RESULTS.md from validation/results.json (numbers are never typed by hand)."""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
r = json.loads((HERE / "results.json").read_text())


def m(d: dict | None) -> str:
    if not d:
        return "| – | – |"
    rc, pc = d.get("rmse_ci"), d.get("pearson_ci")
    rmse = f"{d['rmse']:.1f}" + (f" ({rc[0]:.1f}–{rc[1]:.1f})" if rc else "")
    pear = f"{d['pearson']:.2f}" + (f" ({pc[0]:.2f}–{pc[1]:.2f})" if pc else "") if d.get("pearson") is not None else "–"
    return f"| {rmse} | {pear} |"


def diff(d: dict) -> str:
    return (
        f"RMSE difference {d['rmse_diff']:+.2f} (95% CI {d['rmse_diff_ci'][0]:+.2f} to {d['rmse_diff_ci'][1]:+.2f}); "
        f"correlation difference {d['pearson_diff']:+.3f} (95% CI {d['pearson_diff_ci'][0]:+.3f} to {d['pearson_diff_ci'][1]:+.3f})"
    )


pub = r["published"]
ab = r.get("ablations", {})
wl = r.get("word_level", {})
lines = [
    "# Validation: does the proxy listener match real listeners with hearing loss?",
    "",
    "Generated by `write_results_md.py` from `results.json` (produced by `analyze_v2.py`).",
    "",
    "## Setup",
    "",
    f"- **Data:** Clarity Prediction Challenge 2 (CPC2) evaluation split, tracks 1–3 pooled: {r['n_signals']} hearing-aid-processed sentences in noise, "
    f"{r['n_listeners']} listeners with hearing loss, each with an audiogram and the share of words they repeated correctly (CC BY-SA 4.0).",
    "- **Proxy listener (production code, `hearing/app`):** Cambridge MSBG hearing loss simulation with the listener's audiogram per ear → Whisper; words with probability "
    "< 0.4 count as unclear; prediction = better ear (max over ears) share of prompt words correct. Whether to add an internal noise floor at the ISO 226 threshold before "
    "Whisper was decided on the training split (below).",
    "- **Levels:** in Clarity data 0 dBFS corresponds to 100 dB SPL (https://claritychallenge.org/docs/cec2/data/cec2_data); our MSBG wrapper treats 0 dBFS as 120 dB SPL, "
    "so inputs are offset by −20 dB to present the same sound pressure.",
    f"- **Calibration:** {r['cv']}. Only two numbers are fitted per fold; nothing is trained on CPC2 otherwise.",
    f"- **Uncertainty:** {r['bootstrap']}.",
    f"- **Noise floor:** {r['floor_version']}.",
    "",
    "## Model selection (training split)",
    "",
    "Before looking further at the test set, the noise-floor setting was chosen by a rule written down in advance (`SELECTION.md`, committed before the run): "
    f"Whisper base.en on a seeded subset of {r['selection']['train_n']} CPC2 training sentences, floor on vs off, lower listener-grouped-CV RMSE wins, ties within 0.5 points keep the floor.",
    "",
    "| Training candidate | Calibrated RMSE | Pearson r |",
    "|---|---|---|",
    *[f"| {k} | {v['cal_rmse']:.2f} | {v['cal_pearson']:.3f} |" for k, v in r["selection"]["train_results"].items()],
    "",
    f"**Chosen:** {r['selection']['winner']}. The other setting is reported on the test set under Ablations.",
    "",
    *(
        [
            "Stated plainly: on the test set the setting that was not chosen scores better "
            + ", ".join(f"({k.split(', ')[1]}: RMSE {v['cal']['rmse']:.1f}, r {v['cal']['pearson']:.2f})" for k, v in ab.items() if k.startswith("alternative"))
            + ". It was not adopted because the decision was made on training data, where the two were within the pre-registered tie margin; switching now would be choosing on test labels."
        ]
        if any(k.startswith("alternative") for k in ab)
        else []
    ),
    "",
    "## Results",
    "",
    "Lower RMSE (percentage points of words correct) and higher Pearson correlation are better. Brackets are 95% bootstrap intervals.",
    "",
    "| Method | RMSE | Pearson r |",
    "|---|---|---|",
    "| Proxy listener, Whisper small.en, calibrated " + m(r["ours_cal"]),
    "| Proxy listener, Whisper base.en (deployed), calibrated " + m(r["production_base_en"]["cal"]),
    "| Proxy listener, small.en, uncalibrated " + m(r["ours_raw"]),
    "| Proxy listener, base.en, uncalibrated " + m(r["production_base_en"]["raw"]),
    "| HASPI v2 better-ear, calibrated (same CV) " + m(r["haspi_cal"]),
    "| Audiogram average (PTA) only, calibrated " + m(r["pta_cal"]),
    "| Training-fold mean " + m(r["mean_baseline"]),
    f"| Published CPC2 baseline (HASPI) | {pub['cpc2_baseline_beHASPI']['rmse']} | {pub['cpc2_baseline_beHASPI']['pearson']:.2f} |",
    f"| Best published system (trained on CPC2 training data) | {pub['top_E011_cuervo_marxer']['rmse']} | {pub['top_E011_cuervo_marxer']['pearson']:.2f} |",
    "",
    f"- small.en vs HASPI (paired): {diff(r['paired_ours_cal_minus_haspi_cal'])}.",
    f"- base.en vs HASPI (paired): {diff(r['paired_base_cal_minus_haspi_cal'])}.",
    f"- base.en vs small.en (paired): {diff(r['paired_base_minus_small'])}.",
    f"- Published numbers: {pub['source']}. {pub['note']}",
    "",
    "## Word level",
    "",
    f"On {wl.get('n_signals', '–')} sentences where the listener got some but not all words right, we compared the words the proxy missed with the words the real listener missed "
    f"(from their transcribed responses). Precision {wl.get('precision', 0):.2f}, recall {wl.get('recall', 0):.2f}, F1 {wl.get('f1', 0):.2f}. "
    f"If the proxy placed its misses at random within each sentence, precision would be {wl.get('precision_if_random_within_sentence', 0):.2f}.",
    "",
    "## Ablations",
    "",
]
for name, block in ab.items():
    if not isinstance(block, dict):
        continue
    parts = []
    for k, v in block.items():
        if isinstance(v, dict) and "rmse" in v:
            parts.append(f"{k}: RMSE {v['rmse']:.1f}, r {v['pearson']:.2f}")
        elif isinstance(v, float):
            parts.append(f"{k}: {v:.1f}")
    lines.append(f"- **{name}**: " + "; ".join(parts))
lines += [
    "",
    "## Correction made during this study",
    "",
    "A unit test (`hearing/tests/test_sim.py`) found that the first version of the internal noise floor, an FIR filter design, sat 7–9 dB above the ISO 226 threshold "
    "between 250 and 4000 Hz because the filter could not follow a target spanning more than 40 dB. It was replaced with exact frequency-domain shaping "
    "(band levels now within about 1.5 dB of ISO 226) and the production configurations were decoded again. The earlier results are kept above as "
    "“floor_v1_superseded”. The corrected floor then scored worse than no floor on the test set, which is why the setting was re-decided on the training split "
    "instead of being picked from test results.",
    "",
    "## Limits",
    "",
    "- CPC2 listeners heard hearing-aid-processed signals over headphones; the app simulates free-field speech. The validation checks the listener model, not the whole app.",
    f"- {r['n_listeners']} listeners is a small panel; confidence intervals resample sentences, not listeners.",
    "- The logistic calibration is fitted on test listeners (grouped CV, so never on the listener being predicted). Published systems used the separate training set.",
    "- The deployed app runs Whisper base.en on different hardware (x86 int8 kernels); transcripts can differ slightly from these runs.",
    "",
]
(HERE / "RESULTS.md").write_text("\n".join(lines))
print("wrote RESULTS.md")
